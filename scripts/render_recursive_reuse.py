#!/usr/bin/env python3
"""Render the pre-specified recursive-reuse comparison without new inference."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from evaluate_recursive_reuse import CONFIG, LABELS, load_protocol
from safe_baselines_protocol import ROOT, atomic_json, require_hash, sha256


def render(config_path):
    cfg, _, _, _ = load_protocol(config_path)
    root = ROOT / cfg["output_dir"]
    result = json.loads((root / "RESULTS.json").read_text())
    require_hash(root / "DOCUMENT_SCORES.json", result["document_scores_sha256"])
    require_hash(root / "FULL_POPULATION.json", result["full_population_sha256"])
    scores = json.loads((root / "DOCUMENT_SCORES.json").read_text())
    full = json.loads((root / "FULL_POPULATION.json").read_text())
    manifest = json.loads((root / "INFERENCE_MANIFEST.json").read_text())
    summary = result["summaries"]["three_seed_mean"]["pooled"]
    lines = ["# Direct composition versus recursive reuse", "",
             "Additive post-review tree/active-arity stress test on the same 606 exact-four-child safe prefixes. All three frozen final checkpoints; no merger retraining, teacher encoding, or classifier fitting.", "",
             "Direct: `f4(x1,x2,x3,x4)` (one merge, depth one).",
             "Recursive: `f2(f2(x1,x2),f2(x3,x4))` (three merges, depth two). Each `f2` is the same K4 operator with two active leading slots. Counts are summed exactly at each node.", "",
             "| Representation | Mean teacher cosine | Difference vs direct | ms/document |",
             "| --- | ---: | ---: | ---: |"]
    tex = [r"% Generated by scripts/render_recursive_reuse.py; values from RESULTS.json.",
           r"\begin{table}[H]", r"\caption{Matched 606-prefix tree/reuse stress test. Learned scores average the three checkpoints; flat pooling uses the four input leaves and normalizes once. The recursive tree changes active arity as well as depth. Cost is amortized batched composition on the same device-resident inputs, not batch-one latency.}", r"\label{tab:recursive-reuse}", r"\centering\small", r"\begin{tabularx}{\linewidth}{Yrrr}", r"\toprule",
           r"Representation & Teacher cosine & $\Delta$ vs direct & ms/doc \\", r"\midrule"]
    for method in cfg["methods"]:
        value = summary["metrics"][method]["mean"]
        delta = value - summary["metrics"]["direct_four"]["mean"]
        cost = result["timing"][method]["mean_checkpoint_median_ms_per_document"]
        lines.append(f"| {LABELS[method]} | {value:.6f} | {delta:+.6f} | {cost:.6f} |")
        tex.append(f"{LABELS[method]} & {value:.4f} & {delta:+.6f} & {cost:.4f} " + r"\\")
    tex += [r"\bottomrule", r"\end{tabularx}",
            r"\end{table}"]
    (root / "recursive_reuse_table.tex").write_text("\n".join(tex) + "\n")
    lines += ["", "## Paired contrasts", "", "| Contrast | Mean | Paired 95% CI |", "| --- | ---: | --- |"]
    for name, value in summary["contrasts"].items():
        lines.append(f"| {name} | {value['mean']:+.9f} | [{value['ci95'][0]:+.9f}, {value['ci95'][1]:+.9f}] |")
    similar = summary["metrics"]["direct_recursive_output_cosine"]
    lines += ["", f"Direct–recursive output cosine: **{similar['mean']:.9f}**, conditional 95% CI [{similar['ci95'][0]:.9f}, {similar['ci95'][1]:.9f}].", "",
              "## Per-document degradation", "", "Loss is direct teacher cosine minus recursive teacher cosine; positive means recursion is worse. Statistics below average checkpoint scores within each document, not embeddings or 1,818 independent samples.", ""]
    loss = summary["degradation_direct_minus_recursive"]
    quantiles_text = ", ".join(f"{loss['quantiles'][str(q)]:+.9f}" for q in (0, .05, .5, .95, 1))
    lines += [f"- Fraction degraded: {loss['fraction_degraded']:.6f}",
              f"- Fraction improved: {loss['fraction_improved']:.6f}",
              f"- Loss quantiles (min, p05, median, p95, max): {quantiles_text}"]
    for threshold, fraction in loss["fraction_loss_above"].items():
        lines.append(f"- Fraction losing more than {threshold}: {fraction:.6f}")
    lines += ["", "## Per-checkpoint and per-corpus results", "", "| Checkpoint aggregate | Scope | Documents | Direct | Recursive | Recursive minus direct [95% CI] | Output cosine |", "| --- | --- | ---: | ---: | ---: | --- | ---: |"]
    for seed in [*map(str, cfg["seeds"]), "three_seed_mean"]:
        for scope in result["scope_order"]:
            cell = result["summaries"][seed][scope]
            metrics, delta = cell["metrics"], cell["contrasts"]["recursive_minus_direct"]
            lines.append(f"| {seed} | {scope} | {delta['documents']} | {metrics['direct_four']['mean']:.6f} | {metrics['recursive_binary']['mean']:.6f} | {delta['mean']:+.9f} [{delta['ci95'][0]:+.9f}, {delta['ci95'][1]:+.9f}] | {metrics['direct_recursive_output_cosine']['mean']:.6f} |")
    population = full["pooled"]
    lines += ["", "## Original full-document population", "", "This is descriptive accounting, not a new full-document fidelity test. All global token/leaf/depth histograms match the original frozen results.", "",
              "| Full token range (inclusive) | Documents | Percentage | K4 depth counts |", "| --- | ---: | ---: | --- |"]
    ptex = [r"% Generated from verified full-document population metadata.", r"\begin{table}[H]", r"\caption{Full-document length counts for the 4,000-document population, not the capped prefixes. Counts exclude special tokens. Global token, leaf and depth histograms are verified against the frozen official results; no full-root teacher targets are constructed.}", r"\label{tab:full-length-counts}", r"\centering\small", r"\begin{tabularx}{\linewidth}{Yrr}", r"\toprule", r"Full-document tokens & Documents & Population (\%) \\", r"\midrule"]
    for entry in population["length_bins"]:
        low, high = entry["lower_inclusive"], entry["upper_inclusive"]
        label = f"{low:,}–{high:,}" if high is not None else f">{low - 1:,}"
        texlabel = f"{low:,}--{high:,}" if high is not None else f"$>{low - 1:,}$"
        lines.append(f"| {label} | {entry['documents']} | {entry['fraction'] * 100:.3f} | {entry['depth_counts']} |")
        ptex.append(f"{texlabel} & {entry['documents']:,} & {entry['fraction'] * 100:.3f} " + r"\\")
    ptex += [r"\bottomrule", r"\end{tabularx}",
             r"\end{table}"]
    (root / "full_population_table.tex").write_text("\n".join(ptex) + "\n")
    lines += ["", f"- K4 depth counts: {population['depth_histogram']}",
              f"- Documents with actual recursive reuse (depth >=2): {population['documents_with_recursive_reuse']}/{population['documents']}",
              f"- Strictly above documented {population['context_threshold_tokens']:,}-token context: {population['documents_strictly_above_context']}/{population['documents']} ({population['fraction_strictly_above_context'] * 100:.3f}%).",
              f"- Total: {population['tokens']:,} tokens, {population['leaves']:,} leaves, {population['internal_merges']:,} merges per checkpoint.",
              "", "| Corpus | Depth 1 | Depth 2 | Depth 3 | Above 8,192 tokens |", "| --- | ---: | ---: | ---: | ---: |"]
    for corpus in result["scope_order"][1:]:
        cell = full["by_corpus"][corpus]
        lines.append(f"| {corpus} | {cell['depth_histogram'].get('1', 0)} | {cell['depth_histogram'].get('2', 0)} | {cell['depth_histogram'].get('3', 0)} | {cell['documents_strictly_above_context']} |")
    lines += ["", "## Scope and reproducibility", "",
              "- This is a tree/recursive-reuse stress test, **not a causal estimate of depth alone**: active arity, grouping, intermediate representations and merge count change together.",
              "- Every semantic comparison concerns the same 3,073–4,096-token safe prefix and teacher target. It does not measure fidelity of unrestricted document roots or arbitrary trees/depths.",
              "- Pooling is flat over original leaves. Normalizing intermediate pooled vectors while keeping only token counts would define a different baseline.",
              "- Checkpoints, caches, improvement-1 results and original official results remain unchanged. Direct and flat-pooling vectors are checked against the exact-four subset of improvement 1.",
              "- Intervals use 2,000 shared-document resamples, conditional on the fixed checkpoints. Checkpoint-mean summaries average per-document scores before resampling.",
              f"- GPU: {manifest['environment']['gpu']}; FP32; TF32 disabled; document batch size {cfg['inference']['batch_size']}; both first-level pairs share a 2B-sized call, followed by a B-sized root call.",
              "- Timing excludes cache I/O, transfers and teacher encoding; includes tree packing and all merge calls. Three warm-up and 20 measured passes; checkpoint medians averaged."]
    (root / "REPORT.md").write_text("\n".join(lines) + "\n")

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(7.0, 3.6), constrained_layout=True)
    for seed in cfg["seeds"]:
        values = np.sort([row["degradation_direct_minus_recursive"][str(seed)] for row in scores])
        ax.step(values, np.arange(1, len(values) + 1) / len(values), where="post", linewidth=1, alpha=.55, label=str(seed))
    values = np.sort([row["degradation_direct_minus_recursive"]["three_seed_mean"] for row in scores])
    ax.step(values, np.arange(1, len(values) + 1) / len(values), where="post", color="black", linewidth=1.8, label="Checkpoint-mean score")
    ax.axvline(0, color="gray", linestyle="--", linewidth=.8)
    ax.set(xlabel="Teacher-cosine loss: direct − recursive (positive = worse)", ylabel="Fraction of documents", ylim=(0, 1.01))
    ax.grid(alpha=.2)
    ax.legend(fontsize=8, loc="lower right")
    fig.savefig(root / "degradation_ecdf.png", dpi=180, metadata={"Author": "Mihnea-Teodor Stoica", "Software": "recursive-geodesic-composition"})
    plt.close(fig)
    atomic_json(root / "ARTIFACT_HASHES.json", {str(path.relative_to(root)): sha256(path) for path in sorted(root.rglob("*")) if path.is_file() and path.name != "ARTIFACT_HASHES.json"})
    print(f"Rendered report, tables and empirical loss CDF: {root}", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=CONFIG)
    render(parser.parse_args().config)
